package core

import (
	"context"

	"ariadne/internal/logger"
)

// logRoadWarnings записывает жалобы маршрутизатора в лог.
//
// Раньше все три места, где ядро зовёт маршрутизатор, глотали их подчистую
// (`_`). Стоило это дорого: при отказе разбирающий видел «маршрутизатор ответил
// про слишком мало точек: 45 % из 1200» — и ни слова о том, почему. Лежит ли
// OSRM, отвечает ли мусором, закрыта ли матричная ручка, кончился ли бюджет —
// в логе одна и та же строка на все случаи.
//
// Клиенту это не нужно: у него уже есть `degraded` и итоговое предупреждение.
// А дежурному нужно именно это — первое, что он спросит ночью.
//
// Логгер берём из контекста: там он с номером задачи, положенным воркером.
func logRoadWarnings(ctx context.Context, where string, warns []string) {
	if len(warns) == 0 {
		return
	}
	log := logger.FromContext(ctx)
	for _, w := range warns {
		log.Warn("osrm complained", "where", where, "warning", w)
	}
}
