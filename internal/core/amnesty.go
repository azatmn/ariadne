package core

import (
	"time"

	"ariadne/internal/geo"
)

// Амнистия: кто из попавших под штраф за эпизод доказал невиновность напрямую.
//
// Штраф за эпизод — улика КОСВЕННАЯ: «рядом по времени случился глюк».
// Подделка живёт эпизодами, а не отдельными точками, поэтому расширять штраф
// на окрестность приходится. Но без адвоката это косило честную езду вплотную
// к глюку: 1.3–7.0 % трека на семи маршрутах, включая многочасовые стоянки
// целиком. Точка со снэпом 1 м, идущая 87 км/ч в общем потоке, получала −4.00
// и выбрасывалась.
//
// Принцип: косвенная улика не должна перебивать прямые — снэп, темп соседей,
// связность по времени.

const (
	// AmnestySnapM — точка обязана лежать на дороге: весь довод амнистии в
	// том, что это асфальт, а не поле.
	AmnestySnapM = 30.0

	// AmnestyGap — разрыв больше рвёт цепочку доверия. Через дыру связи
	// ручаться нельзя: за ней машина могла оказаться где угодно.
	AmnestyGap = 3 * time.Minute

	// AmnestyVmaxKmh — и переход обязан быть физически нормальным.
	AmnestyVmaxKmh = 110.0

	// AmnestyRunMin — длина связной серии, которой хватает, чтобы ручаться за
	// себя без внешнего поручителя.
	//
	// Нужно там, где глюки идут густо и чистых точек рядом не остаётся вовсе:
	// в Шубине правило островов пометило 13 кусков верно, но окна штрафа
	// перекрылись и накрыли честный кусок из 43 точек — первому адвокату не
	// от чего было стартовать.
	AmnestyRunMin = 15
)

// FindAmnesty возвращает точки, оправданные напрямую.
//
// Два независимых довода:
//
//  1. Примыкание к заведомо чистой точке. Идём от точек вне подозрения наружу
//     в обе стороны по времени и пускаем доверие дальше, пока переход остаётся
//     плотным, а точка — на дороге.
//  2. Длинная связная серия. Если подряд идёт AmnestyRunMin и более точек, все
//     на асфальте, все связаны возможными переходами и ни одна не уличена
//     лично, — этого довода достаточно и без внешнего поручителя.
//
// spread — попавшие под штраф за эпизод (включая точки в приманках).
// bad — уличённые ЛИЧНО (лётное поле, ловушка, огрызок, слабый поток): их не
// оправдывает ничто, и они же рвут цепочку доверия. Иначе связная подделка
// оправдала бы сама себя — она как раз связная и лежит на дорогах.
// decoy — сила улики места по приманкам; может быть nil или короче трека.
func FindAmnesty(
	pts []geo.Point,
	snaps []float64, hasSnap []bool,
	spread, bad map[int]struct{},
	decoy []float64,
) map[int]struct{} {
	n := len(pts)
	amn := make(map[int]struct{})
	if n == 0 {
		return amn
	}

	// Вне подозрения — значит может поручиться за соседа.
	free := make([]bool, n)
	for i := range n {
		_, suspected := spread[i]
		_, convicted := bad[i]
		free[i] = !suspected && !convicted
	}

	onRoad := func(i int) bool {
		return i < len(snaps) && i < len(hasSnap) && hasSnap[i] && snaps[i] <= AmnestySnapM
	}

	linked := func(a, b int) bool {
		dt := pts[b].Time.Sub(pts[a].Time)
		if dt < 0 {
			dt = -dt
		}
		if dt > AmnestyGap {
			return false
		}
		return geo.Haversine(pts[a], pts[b]) <= dt.Seconds()*AmnestyVmaxKmh/3.6+ChainSlackM
	}

	// Довод 1. Проходим в обе стороны: глюк одинаково часто стоит и до
	// честной езды, и после неё, поэтому одного направления мало.
	walk := func(from, stop, step int) {
		trusted := -1
		for i := from; i != stop; i += step {
			if free[i] {
				trusted = i
				continue
			}
			if _, convicted := bad[i]; convicted {
				trusted = -1 // сквозь уличённого доверие не идёт
				continue
			}
			if trusted < 0 {
				continue
			}
			if onRoad(i) && linked(trusted, i) {
				amn[i] = struct{}{}
				trusted = i // оправданный сам становится поручителем
				continue
			}
			trusted = -1
		}
	}
	walk(0, n, 1)
	walk(n-1, -1, -1)

	// Довод 2. Серия ручается за себя сама.
	var run []int
	flush := func() {
		defer func() { run = run[:0] }()
		if len(run) < AmnestyRunMin {
			return
		}
		// Приманка — прямая улика МЕСТА, и связность её не перебивает: две
		// длинные серии в замере топтались на двухстах метрах внутри
		// приманочной клетки. Хватает одной такой точки, чтобы отказать всей
		// серии.
		for _, i := range run {
			if i < len(decoy) && decoy[i] > 0 {
				return
			}
		}
		for _, i := range run {
			amn[i] = struct{}{}
		}
	}

	for i := range n {
		_, suspected := spread[i]
		_, convicted := bad[i]
		fits := suspected && !convicted && onRoad(i)

		switch {
		case fits && len(run) > 0 && !linked(run[len(run)-1], i):
			flush() // серия оборвалась по времени — начинаем новую
		case !fits && len(run) > 0:
			flush()
		}
		if fits {
			run = append(run, i)
		}
	}
	flush()

	return amn
}
