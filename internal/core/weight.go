package core

import (
	"math"
	"slices"
	"time"

	"ariadne/internal/geo"
)

// Вес точки — насколько мы ей верим. Считается от расстояния до ближайшей
// дороги: цепочка набирает сумму весов, и точка, которой не верят, тянет сумму
// вниз, поэтому обходить её выгоднее, чем брать.
const (
	// SnapSigmaM — разброс ошибки приёмника, метры. Вес падает по гауссиане от
	// расстояния до дороги — так же, как считает вероятность классический map
	// matching (Newson & Krumm): ошибка приёмника распределена нормально,
	// поэтому точка в 25 м от асфальта правдоподобна, а в 150 м почти нет.
	//
	// Линейное падение пробовали, оказалось слишком мягким: спуфинг в
	// Шереметьеве со снэпом 100 м получал вес 0.73, почти как честная точка
	// на трассе, и проходил.
	SnapSigmaM = 25.0

	// Точность у приборов разная: у большинства треков медиана снэпа 4–6 м, но
	// попадаются с 76 м, и там фиксированный порог выбрасывал больше половины
	// точек, лежащих вдоль настоящей трассы. Поэтому σ оцениваем из самого
	// трека, но не даём ей уйти ни слишком низко, ни слишком высоко.
	//
	// Нижняя граница равна базовой σ намеренно: адаптация нужна, чтобы
	// ОСЛАБИТЬ требования на треках с плохим приёмником, а не ужесточить их на
	// хороших. С границей 15 м выброс на честном МКАД подрос с 3.1 % до 4.1 %.
	SigmaMinM       = 25.0
	SigmaMaxM       = 60.0
	SigmaFromMedian = 2.0

	// SnapPenalty — насколько глубоко вес уходит в минус.
	//
	// Уходить в минус обязательно. Цепочка набирает СУММУ весов, поэтому при
	// любых положительных весах ей выгодно взять всё, до чего дотягивается
	// физика: точка с весом 0.02 всё равно лучше, чем её отсутствие. Штраф
	// делает крюк в спуфинг невыгодным — цепочка предпочтёт обойти его.
	// Ноль приходится примерно на 30 м от дороги.
	SnapPenalty = 1.0

	// SmoothWindow — окно сглаживания веса, по ВРЕМЕНИ.
	//
	// Окно раньше задавалось в точках (±2), и это была та же ошибка, что с
	// допуском скорости: при частой записи оно вырождается. На `ab681145` трек
	// полтора километра идёт полем со снэпами 100–436 м, но точки капают раз в
	// пять секунд, и пять подряд случайно легли на деревенскую грунтовку.
	// Окно в ±2 соседа их не перебивает; окно в ±60 секунд захватывает весь
	// кусок, и медиана возвращает ему истинные сто метров.
	SmoothWindow = 60 * time.Second

	// Границы числа соседей: меньше двух не берём даже при редкой записи,
	// иначе сглаживание вырождается в тождество; больше тридцати не берём,
	// иначе на частой записи медиана размажет весь трек.
	SmoothMinNeighbours = 2
	SmoothMaxNeighbours = 30
)

// SigmaOf оценивает разброс ошибки приёмника по самому треку.
// Неотвеченные точки в оценку не входят: ноль вместо «неизвестно» занизил бы
// медиану и сделал бы требования строже там, где мы просто ничего не знаем.
func SigmaOf(snaps []float64, ok []bool) float64 {
	valid := make([]float64, 0, len(snaps))
	for i, s := range snaps {
		if i < len(ok) && ok[i] {
			valid = append(valid, s)
		}
	}
	if len(valid) == 0 {
		return SnapSigmaM
	}
	return min(SigmaMaxM, max(SigmaMinM, median(valid)*SigmaFromMedian))
}

// Weight — вес точки по её расстоянию до дороги.
//
// hasSnap=false означает, что OSRM промолчал. Вес тогда ровно ноль: ноль
// метров означал бы «точка на дороге», то есть сильный довод ЗА неё, а
// молчание не довод ни за, ни против.
func Weight(snap float64, hasSnap bool, sigma float64) float64 {
	if !hasSnap {
		return 0
	}
	if sigma <= 0 {
		sigma = SnapSigmaM
	}
	g := math.Exp(-(snap * snap) / (2 * sigma * sigma))
	return (1.0+SnapPenalty)*g - SnapPenalty
}

// Smooth сглаживает веса медианой по соседям в окне ВРЕМЕНИ.
//
// Зачем: спуфинг-облако иногда случайно накрывает настоящую дорогу, и отдельная
// его точка получает снэп в метр и полный вес. В Шереметьеве таких оказалось
// две из двадцати четырёх — и цепочка ради них делала два захода в аэропорт.
// Одинокая хорошая точка среди плохих — совпадение, а не свидетельство.
//
// Медиана, а не среднее: на стыке честного участка с глючным среднее утягивает
// вниз последние правильные точки, медиана их удерживает.
func Smooth(w []float64, pts []geo.Point, window time.Duration) []float64 {
	n := len(w)
	out := make([]float64, n)
	if n == 0 {
		return out
	}

	buf := make([]float64, 0, 2*SmoothMaxNeighbours+1)
	usePts := pts != nil && len(pts) == n && window > 0

	for i := range w {
		lo := max(0, i-SmoothMinNeighbours)
		hi := min(n, i+SmoothMinNeighbours+1)

		if usePts {
			t := pts[i].Time
			for lo > 0 && t.Sub(pts[lo-1].Time) <= window && i-lo < SmoothMaxNeighbours {
				lo--
			}
			for hi < n && pts[hi].Time.Sub(t) <= window && hi-i < SmoothMaxNeighbours {
				hi++
			}
		}

		// Буфер переиспользуем: медиана считается на каждую точку трека, и
		// копия среза на каждом шаге дала бы выделение памяти на точку —
		// пятьдесят тысяч выделений на большом треке впустую.
		buf = append(buf[:0], w[lo:hi]...)
		out[i] = medianInPlace(buf)
	}
	return out
}

// PointWeights — готовые веса точек: оценка σ по треку, вес по снэпу,
// сглаживание НА ПОНИЖЕНИЕ.
//
// Понижение здесь принципиально. Медиана симметрична и так же вытягивает
// НАВЕРХ одинокую плохую точку среди хороших: на `749dc894` у Фенино так
// выживала точка со снэпом 132 м — сырой вес −1.00, после сглаживания +0.98.
// Проверка дорисовкой показала, что это не косметика: маршрут по дорогам через
// неё давал 28.11 км против 15.86 км мимо, то есть двенадцать километров
// выдуманного пробега.
//
// Точка не может быть достовернее своего окружения, но может быть хуже —
// отсюда минимум из сырого и сглаженного.
func PointWeights(pts []geo.Point, snaps []float64, ok []bool) []float64 {
	n := len(pts)
	out := make([]float64, n)
	if n == 0 {
		return out
	}

	sigma := SigmaOf(snaps, ok)
	raw := make([]float64, n)
	for i := range raw {
		if i < len(snaps) && i < len(ok) {
			raw[i] = Weight(snaps[i], ok[i], sigma)
		}
	}

	smoothed := Smooth(raw, pts, SmoothWindow)
	for i := range out {
		out[i] = min(raw[i], smoothed[i])
	}
	return out
}

// median — середина набора, не портя вход.
//
// На чётной длине это среднее двух средних, ровно как в питоновской
// statistics.median: возьми мы нижнее из них, все веса сдвинулись бы, и
// сверка с прототипом перестала бы сходиться.
func median(v []float64) float64 {
	if len(v) == 0 {
		return 0
	}
	return medianInPlace(slices.Clone(v))
}

// medianInPlace — то же самое, но переставляет элементы переданного среза.
// Для тех, у кого на руках уже копия и лишнее выделение памяти ни к чему.
func medianInPlace(s []float64) float64 {
	if len(s) == 0 {
		return 0
	}
	slices.Sort(s)
	mid := len(s) / 2
	if len(s)%2 == 1 {
		return s[mid]
	}
	return (s[mid-1] + s[mid]) / 2
}
