// Package core — алгоритм очистки трека по дорожной сети.
//
// Отделён от pipeline намеренно: в конвейере он занимает одну стадию, но внутри
// это самостоятельная предметная область — стоянки, веса точек, правила поиска
// подделки и выбор самой тяжёлой физически связной цепочки. Отдельным пакетом
// его можно проверять без конвейера и переиспользовать в дорисовке.
package core

import (
	"time"

	"ariadne/internal/geo"
)

// --- стоянки ---------------------------------------------------------------

const (
	// StopRadiusM — пятно, внутри которого считаем, что машина стоит.
	// Радиус щедрый: у стоящей машины координата гуляет на десятки метров
	// из-за переотражений сигнала и смены созвездия спутников.
	StopRadiusM = 150.0

	// StopMinStay — короче этого не стоянка, а светофор или пробка.
	StopMinStay = 5 * time.Minute

	// StopTrustStay — с какой длительности стоянка получает привилегию в весах.
	// Порог взят по разметке пользователя: полчаса оказалось вдвое строже
	// нужного — при нём правило признавало 67 настоящих стоянок из 96, при
	// четверти часа 95. Ниже 15 минут сознательно не опускаемся: пользователь
	// размечал начиная с этого порога, про более короткие данных нет.
	StopTrustStay = 15 * time.Minute

	// StopSpanMinM — стоящая машина обязана дрожать.
	// Разделение по этому признаку на разметке идеальное: из 96 настоящих
	// стоянок НИ ОДНОЙ с разбросом меньше 20 м, из 18 ложных — 11, причём
	// у десяти координата повторяется байт в байт.
	StopSpanMinM = 20.0

	// FrozenSpanM — ниже этого разброса стоянка признаётся залипанием трекера:
	// место показано верно, но устарело, машина уже уехала.
	FrozenSpanM = 5.0

	// StopMaxSnapM — дальше этого от дороги «стоянка» доверия не заслуживает.
	// Порог щедрый, потому что фуры ночуют на базах и складских площадках,
	// которых в дорожном графе нет: в разметке есть честные стоянки со снэпом
	// 113, 122 и 515 м. Но 700 м без дороги фура не проедет — это уже не
	// «нет в OSM», а «проезда нет». На этом пороге не страдает ни одна
	// настоящая стоянка и отсекаются три ложных.
	StopMaxSnapM = 700.0

	// StopGapFrac — если одна дыра съела такую долю времени «стоянки», это
	// не стоянка, а два куска движения по краям обрыва связи.
	StopGapFrac = 0.8

	// Выезд из настоящей стоянки происходит с земной скоростью.
	StopOutMaxKmh = 150.0
	// Кандидатами на выезд считаем только точки, реально ушедшие с места:
	// за залипшей координатой стоят её же повторы со скоростью ноль, и
	// телепорт следом за ними иначе никто не увидит.
	StopOutMinM   = 200.0
	StopOutWindow = 15 * time.Minute
	// Смотрим несколько ушедших точек и берём лучшую: сразу за честной
	// стоянкой часто стоит одиночный глюк, и по одной точке она осуждалась бы зря.
	StopOutLook = 5
)

// StopRange — интервал стоянки: индексы первой и последней точки, включительно.
type StopRange struct {
	Start, End int
}

// Len — сколько точек в интервале.
func (s StopRange) Len() int { return s.End - s.Start + 1 }

// FindStops находит интервалы, где машина никуда не уезжала.
//
// Пятно растёт от точки Start, и каждая следующая точка меряется от ЦЕНТРА
// накопленного пятна, а не от первой точки. Это важно: мерь мы от первой,
// медленный ход зачёлся бы за стоянку — точки уползали бы по цепочке, каждая
// недалеко от предыдущей, и трек потерял бы километры.
//
// Интервалы не пересекаются: каждая точка принадлежит не более чем одной
// стоянке. На это опирается всё дальнейшее — и веса, и дорисовка.
func FindStops(pts []geo.Point, radius float64, minStay time.Duration) []StopRange {
	var stops []StopRange
	n := len(pts)

	for i := 0; i < n; {
		// Отсечка по остатку времени. Рост пятна стоит тем дороже, чем пятно
		// длиннее, и на плотном сгустке, где ни одна серия не дотягивает до
		// порога, работа становится квадратичной: внутренний цикл каждый раз
		// доходит до конца сгустка, внешний сдвигается на единицу.
		// Замер: 20 тысяч таких точек — 4.5 секунды, на пределе в 50 тысяч
		// сервис встал бы. Настоящие треки этим не страдают (123 тысячи точек
		// разбираются за доли секунды), но негодный вход присылают не спросив.
		//
		// Проверка дешёвая и точная: время от i до конца трека — это верхняя
		// граница длительности любой стоянки, начинающейся в i. Не хватило её —
		// не хватит и никакой следующей точке, потому что с ростом i остаток
		// только убывает.
		if pts[n-1].Time.Sub(pts[i].Time) < minStay {
			break
		}

		sumLon, sumLat := pts[i].Lon, pts[i].Lat
		cnt := 1.0
		j := i

		for j+1 < n {
			center := geo.Point{Lon: sumLon / cnt, Lat: sumLat / cnt}
			if geo.Haversine(center, pts[j+1]) > radius {
				break
			}
			j++
			sumLon += pts[j].Lon
			sumLat += pts[j].Lat
			cnt++
		}

		if j > i && pts[j].Time.Sub(pts[i].Time) >= minStay {
			stops = append(stops, StopRange{Start: i, End: j})
			i = j + 1
			continue
		}
		i++
	}
	return stops
}

// StopOwner — сопоставление «номер точки → номер стоянки».
//
// Нужно там, где важно не «стоит ли точка в стоянке», а «в КАКОЙ именно».
// Дорисовка на этом держится: переход внутри одной стоянки — дрожание, и
// рисовать дорогу между двумя дрожаниями бессмысленно; а переход из стоянки
// наружу — это выезд, самый обычный перегон, и его дорисовывать надо.
func StopOwner(total int, stops []StopRange) map[int]int {
	owner := make(map[int]int, len(stops)*8)
	for k, s := range stops {
		for i := s.Start; i <= s.End && i < total; i++ {
			if i >= 0 {
				owner[i] = k
			}
		}
	}
	return owner
}

// IsFrozen — залипла ли координата.
//
// Приёмник всегда шумит: даже у стоящей машины точки гуляют на метры.
// Координата, повторённая шестьдесят раз подряд, — это не измерение, а повтор
// последнего известного значения. Такая точка показывает, где машина БЫЛА,
// а не где она есть, и опорой в цепочке служить не может.
func IsFrozen(pts []geo.Point, s StopRange) bool {
	return spanMeters(pts, s) < FrozenSpanM
}

// TrustedStop — настоящая ли это стоянка.
//
// Пять условий, каждое отсекает свой вид подделки:
//
//	длительность  короче четверти часа привилегий не даём вообще;
//	место         стоянка в чистом поле их не получает;
//	связность     одна дыра во всё время — это обрыв связи, а не стоянка;
//	дрожание      стоящая машина шумит, залипшая координата нет;
//	выезд         из настоящей стоянки уезжают с земной скоростью.
//
// snap — расстояние до ближайшей дороги; hasSnap=false означает, что OSRM
// промолчал, и это не улика: молчание не довод ни за, ни против.
func TrustedStop(pts []geo.Point, s StopRange, snap float64, hasSnap bool) bool {
	if s.Start < 0 || s.End >= len(pts) || s.Start > s.End {
		return false
	}

	dur := pts[s.End].Time.Sub(pts[s.Start].Time)
	if dur < StopTrustStay {
		return false
	}
	if hasSnap && snap > StopMaxSnapM {
		return false
	}

	// Самая длинная дыра внутри «стоянки» против всей её длительности.
	var maxGap time.Duration
	for i := s.Start; i < s.End; i++ {
		if g := pts[i+1].Time.Sub(pts[i].Time); g > maxGap {
			maxGap = g
		}
	}
	if dur > 0 && float64(maxGap)/float64(dur) > StopGapFrac {
		return false
	}

	if spanMeters(pts, s) < StopSpanMinM {
		return false
	}

	return exitPlausible(pts, s.End)
}

// exitPlausible — можно ли уехать из точки end с земной скоростью.
//
// Смотрим только точки, РЕАЛЬНО ушедшие с места. Прежняя версия брала минимум
// скорости среди пяти следующих записей и обманывалась залипанием: за ним стоят
// его же повторы со скоростью ноль, минимум выходил нулевым, и телепорт следом
// никто не видел. Под Рязанью так уцелела заморозка, из которой трек уходит
// на 47 км за 19 секунд — 8905 км/ч.
func exitPlausible(pts []geo.Point, end int) bool {
	best, seen := 0.0, 0
	found := false

	for k := end + 1; k < len(pts); k++ {
		dt := pts[k].Time.Sub(pts[end].Time)
		if dt > StopOutWindow {
			break
		}
		d := geo.Haversine(pts[end], pts[k])
		if d < StopOutMinM {
			continue // с места ещё не ушёл — это продолжение стоянки
		}
		sec := dt.Seconds()
		if sec < 1 {
			sec = 1
		}
		v := d / sec * 3.6
		if !found || v < best {
			best, found = v, true
		}
		if seen++; seen >= StopOutLook {
			break
		}
	}

	// Выезда нет вовсе — например, стоянка в конце трека. Это не улика.
	return !found || best <= StopOutMaxKmh
}

// spanMeters — диагональ прямоугольника, накрывающего точки интервала.
func spanMeters(pts []geo.Point, s StopRange) float64 {
	if s.Start < 0 || s.End >= len(pts) || s.Start > s.End {
		return 0
	}
	minLon, maxLon := pts[s.Start].Lon, pts[s.Start].Lon
	minLat, maxLat := pts[s.Start].Lat, pts[s.Start].Lat
	for i := s.Start + 1; i <= s.End; i++ {
		minLon = min(minLon, pts[i].Lon)
		maxLon = max(maxLon, pts[i].Lon)
		minLat = min(minLat, pts[i].Lat)
		maxLat = max(maxLat, pts[i].Lat)
	}
	return geo.Haversine(
		geo.Point{Lon: minLon, Lat: minLat},
		geo.Point{Lon: maxLon, Lat: maxLat},
	)
}
