package core

import (
	"math"

	"ariadne/internal/geo"
)

// Выбор цепочки — сердце алгоритма.
//
// Из трека выбирается самая тяжёлая физически связная последовательность точек:
// цепочка набирает СУММУ весов и обязана состоять из переходов, которые машина
// физически могла проехать. Всё остальное — стоянки, правила, проверка по
// дорогам — лишь готовит веса и запреты для этого выбора.
//
// Почему именно так, а не поточечной фильтрацией: локальный фильтр решает по
// одному соседу, и одна плохая опора убивает всё за ней. На `9379e03e` так
// терялось 544 точки подряд — фильтр скорости зацепился за глюк, и вся честная
// езда после него мерилась от глюка. Выбор цепочки сравнивает варианты целиком
// и такой ошибки не делает по построению.

const (
	// ChainVmaxKmh — физический предел фуры.
	ChainVmaxKmh = 110.0

	// ChainSlackM — допуск на погрешность координаты при коротких промежутках.
	// Без него 300 м за пять секунд дают формальные 216 км/ч, хотя это
	// дрожание стоящей машины.
	ChainSlackM = 300.0

	// ChainLookback — насколько далеко назад цепочка ищет предшественника.
	//
	// Ограничение техническое, не физическое, и при 500 оно начинало решать за
	// алгоритм: на `4daf8725` между двумя честными точками лежало 700 точек
	// спуфинг-облака, прямой переход между ними был законен (37 км за 2 часа),
	// но окна не хватало — и цепочка была ВЫНУЖДЕНА взять точку из середины
	// облака. Расширение не стоило ничего: цепочка строится чище, цикл сходится
	// за меньшее число проходов, прогон даже ускорился.
	ChainLookback = 2000

	// BanCellM — размер клетки, по которой опознаётся запрещённый переход.
	BanCellM = 50.0
)

// BanID — ключ запрещённого перехода: пара клеток, откуда и куда.
//
// Ключ по МЕСТУ, а не по времени. Точка, повторённая трекером десять раз
// подряд, даёт десять разных времён, и при ключе по времени это были бы десять
// отдельных запретов: запретили пару (7512, 7758) — цепочка взяла (7511, 7758),
// у неё другое время и другой ключ. Двенадцати проходов не хватало, чтобы
// перебрать все дубли одной координаты.
type BanID struct {
	fromY, fromX int
	toY, toX     int
}

// BanKey — ключ перехода между двумя точками.
func BanKey(a, b geo.Point) BanID {
	ay, ax := banCell(a)
	by, bx := banCell(b)
	return BanID{fromY: ay, fromX: ax, toY: by, toX: bx}
}

func banCell(p geo.Point) (int, int) {
	// RoundToEven, а не Round: половинки округляются к чётному, как это делает
	// питоновский round. Разница вылезает ровно на границах клеток — точка,
	// попавшая на 2.5 клетки, уходит во вторую вместо третьей, — и даёт другой
	// ключ запрета. На `4daf8725` из-за этого получалось 225 запретов вместо
	// 223 у прототипа: две точки легли по разные стороны границы.
	y := math.RoundToEven(p.Lat * 111320.0 / BanCellM)
	x := math.RoundToEven(p.Lon * 111320.0 * math.Cos(p.Lat*math.Pi/180) / BanCellM)
	return int(y), int(x)
}

// Reachable — успела бы машина проехать от a до b.
//
// Меряем по ПРЯМОЙ: она короче любой дороги, значит ложных запретов не даёт.
// Но и пропускает случаи, где дорога заметно длиннее — 42 км по прямой за 42
// минуты выглядят как 60 км/ч, а по асфальту там 122 км, то есть 171 км/ч.
// Такие переходы ловит проверка по дорогам и складывает в `banned`.
//
// В `banned` лежит не «нельзя никогда», а МИНИМАЛЬНОЕ время, за которое переход
// вообще проходим по дорогам. Так физически честнее: между теми же двумя
// местами машина может проехать позже, когда времени хватит, и запрет,
// поставленный на коротком проезде, не должен закрывать её навсегда.
func Reachable(a, b geo.Point, banned map[BanID]float64) bool {
	dt := b.Time.Sub(a.Time).Seconds()
	if dt < 0 {
		return false
	}
	if len(banned) > 0 {
		if need, ok := banned[BanKey(a, b)]; ok && dt < need {
			return false
		}
	}
	return geo.Haversine(a, b) <= ChainVmaxKmh/3.6*dt+ChainSlackM
}

// BuildChain выбирает самую тяжёлую физически связную цепочку точек.
// Возвращает индексы в порядке возрастания.
//
// Кроме ближних кандидатов из окна просмотра рассматривается ОПОРА — лучшая
// точка за его пределами. Без неё ограничение на просмотр решает за алгоритм:
// когда между двумя честными точками лежит больше точек мусора, чем помещается
// в окно, цепочка не может соединить их напрямую и вынуждена зацепиться за
// что-то внутри облака, даже если у всего облака вес отрицательный.
//
// Поднимать окно бессмысленно — это заплатка, и найдётся место, где не хватит
// и двадцати тысяч. Вместо этого ведём накопительный максимум и держим его
// лучшего представителя как кандидата. Стоимость — одна проверка на точку
// вместо целого окна, а поведение меняется ТОЛЬКО там, где опора лежит за его
// пределами, то есть где алгоритм иначе слеп.
func BuildChain(pts []geo.Point, w []float64, banned map[BanID]float64) []int {
	n := len(pts)
	if n == 0 {
		return nil
	}
	if n > len(w) {
		n = len(w)
	}
	if n == 1 {
		return []int{0}
	}

	best := make([]float64, n) // лучший суммарный вес цепочки, кончающейся здесь
	prev := make([]int, n)     // откуда пришли
	pmax := make([]float64, n) // накопительный максимум best
	pidx := make([]int, n)     // и его представитель

	copy(best, w[:n])
	for i := range prev {
		prev[i] = -1
	}
	pmax[0], pidx[0] = best[0], 0

	for j := 1; j < n; j++ {
		lo := max(0, j-ChainLookback)
		bj, pj := w[j], -1

		for i := j - 1; i >= lo; i-- {
			if best[i]+w[j] > bj && Reachable(pts[i], pts[j], banned) {
				bj, pj = best[i]+w[j], i
			}
		}

		// Опора за пределами окна. Проверяем только если окно вообще не
		// покрывает начало трека — иначе кандидат уже рассмотрен выше.
		if lo > 0 {
			if i := pidx[lo-1]; i >= 0 && best[i]+w[j] > bj &&
				Reachable(pts[i], pts[j], banned) {
				bj, pj = best[i]+w[j], i
			}
		}

		best[j], prev[j] = bj, pj
		if best[j] >= pmax[j-1] {
			pmax[j], pidx[j] = best[j], j
		} else {
			pmax[j], pidx[j] = pmax[j-1], pidx[j-1]
		}
	}

	// Конец цепочки — точка с наибольшей суммой. При равенстве берём ПЕРВУЮ:
	// иначе результат зависел бы от порядка перебора, а километраж обязан быть
	// воспроизводимым.
	end := 0
	for k := 1; k < n; k++ {
		if best[k] > best[end] {
			end = k
		}
	}

	var out []int
	for k := end; k != -1; k = prev[k] {
		out = append(out, k)
	}
	for i, j := 0, len(out)-1; i < j; i, j = i+1, j-1 {
		out[i], out[j] = out[j], out[i]
	}
	return out
}
