package osrm

import (
	"context"
	"fmt"
	"runtime/debug"

	"ariadne/internal/logger"
)

// panicErr превращает пойманную панику в обычную ошибку и пишет её в лог со
// стеком.
//
// Зачем это нужно. Воркер уже ловит паники (`worker.runFill`) и превращает их
// в упавшую ЗАДАЧУ — сервис при этом живёт дальше. Но `recover` работает только
// в своей горутине, а этот пакет запускает дочерние: батчи снэпов, куски
// матрицы, пары маршрутов. Паника в любой из них проходит мимо воркера и валит
// ВЕСЬ процесс со всеми задачами в полёте.
//
// Это не догадка: ответ OSRM с матрицей нужной высоты, но короткими строками,
// ронял сервис целиком, и `restart: unless-stopped` поднимал его под следующий
// такой же ответ. Дыру в разборе матрицы закрыли (`matrixShape`), но чинить
// такое поштучно нельзя — следующая ошибка с индексом сделает то же самое.
//
// Стек пишем обязательно: наверх уедет короткая строка, и без стека искать
// место придётся по всему пакету. Логгер берём из контекста — там же, где его
// оставил вызывающий.
//
// Возвращаем ошибку, а не глотаем: каждое место само решает, чем стала паника —
// предупреждением, неотвеченной парой или неудавшимся куском. Молча продолжать
// с испорченными данными нельзя.
func panicErr(ctx context.Context, where string, r any) error {
	logger.FromContext(ctx).Error("panic in osrm goroutine",
		"where", where, "panic", r, "stack", string(debug.Stack()))
	return fmt.Errorf("%s: failed while parsing the response: %v", where, r)
}
