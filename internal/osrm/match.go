package osrm

// Почему в этом пакете нет map matching (ручки /match).
//
// Изначально здесь лежала заготовка под /match — ручку, которая сажает весь
// трек на дорожную сеть разом. Замысел был очевидный: подделанные участки не
// лягут на дороги и отсеются сами. Замер показал, что так не выходит, и от
// ручки отказались по трём независимым причинам.
//
// ПЕРВОЕ. Она работает хуже самодельной чистки. Проверено на размеченных
// маршрутах: /match честно сажает на дороги И спуфинг тоже, потому что
// подделка тоже рисуется по дорогам. Посаженная на дорожную сеть подделка
// становится неотличима от честной езды — то есть ручка не отсеивает мусор,
// а придаёт ему законный вид.
//
// ВТОРОЕ. Её нет на боевом сервере: `osrm.trucks.ru` отвечает 404 на /match,
// /table и /nearest. Решение, построенное на /match, туда просто не поедет.
//
// ТРЕТЬЕ. Она опасна на наших данных. Документированный лимит — сотня
// координат за запрос, а треки, где точки лежат дальше сотни метров от дороги,
// вешают match-плагин надолго, вплоть до заморозки сервера. У нас именно такие
// треки: спуфинг уводит точки в поля.
//
// Вместо неё используются /route (снэпы и геометрия) и /table (расстояния
// пачками) — см. snap.go, pairs.go, route.go. Дорожная сеть при этом всё равно
// работает на нас, но не как чистилка, а как мера: насколько точка отстоит от
// дороги и был ли переход между двумя точками физически возможен.
