package geo

// SegmentsIntersect — пересекаются ли отрезки a1a2 и b1b2. Касание концом и
// налегание коллинеарных отрезков считаются пересечением.
//
// Долгота и широта берутся как координаты плоскости, без поправки на сжатие
// меридианов. На предикат «пересекаются или нет» это не влияет: растяжение
// одной оси умножает все векторные произведения на общий положительный
// множитель, а решение принимается по их знакам. Расстояний функция не
// считает, поэтому искажать нечего.
//
// Сейчас не вызывается: стадия, убиравшая самопересечения трека, из конвейера
// убрана — петли разбираются в ядре по весам, а не по геометрии.
func SegmentsIntersect(a1, a2, b1, b2 Point) bool {
	d1 := cross(a1, a2, b1)
	d2 := cross(a1, a2, b2)
	d3 := cross(b1, b2, a1)
	d4 := cross(b1, b2, a2)

	if ((d1 > 0 && d2 < 0) || (d1 < 0 && d2 > 0)) &&
		((d3 > 0 && d4 < 0) || (d3 < 0 && d4 > 0)) {
		return true
	}

	if d1 == 0 && onSegment(a1, a2, b1) {
		return true
	}
	if d2 == 0 && onSegment(a1, a2, b2) {
		return true
	}
	if d3 == 0 && onSegment(b1, b2, a1) {
		return true
	}
	if d4 == 0 && onSegment(b1, b2, a2) {
		return true
	}

	return false
}

// cross — знак векторного произведения oa × ob: с какой стороны от луча oa
// лежит точка b. Положительно — слева, отрицательно — справа, ноль — на одной
// прямой.
func cross(o, a, b Point) float64 {
	return (a.Lon-o.Lon)*(b.Lat-o.Lat) - (b.Lon-o.Lon)*(a.Lat-o.Lat)
}

// onSegment — лежит ли r внутри прямоугольника, натянутого на p и q.
// Вызывается только когда r уже признана коллинеарной pq, поэтому проверки
// рамки достаточно.
func onSegment(p, q, r Point) bool {
	return min(p.Lon, q.Lon) <= r.Lon && r.Lon <= max(p.Lon, q.Lon) &&
		min(p.Lat, q.Lat) <= r.Lat && r.Lat <= max(p.Lat, q.Lat)
}
